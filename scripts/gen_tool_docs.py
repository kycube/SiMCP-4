"""Generate docs/TOOLS.md from what the server actually advertises over MCP (tools/list), and check that every tool
is documented well enough for any client (Claude, OpenAI, Gemini...).

    python scripts/gen_tool_docs.py           # write docs/TOOLS.md
    python scripts/gen_tool_docs.py --check   # fail if a reference is stale or a tool breaks the portability rules

Portability rules checked (the strictest common limits of the major clients):
- every parameter has a description (clients pass only the JSON schema to their models);
- tool descriptions <= 1024 characters (OpenAI's function description limit);
- tool names match ^[a-zA-Z0-9_-]{1,64}$;
- input schemas use only object / string / integer / number / boolean / array (with items) / null, no $ref or
  $defs, and anyOf only as "T or null";
- every tool carries MCP annotations (readOnlyHint, destructiveHint, idempotentHint, openWorldHint).
"""

from __future__ import annotations

import asyncio
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
# server module -> (generated reference, title, what its "act" / "destructive" kinds touch)
SERVERS = {
    "sc4_mcp.server": ("TOOLS.md", "SimCity 4 server (simcity4)", "the game",
                       "can discard or destroy something (unsaved city, a file, the game process)",
                       "`guide` (markdown)"),
}
SIMPLE = {"object", "string", "integer", "number", "boolean", "array", "null"}


def type_of(sch: dict) -> str:
    if "anyOf" in sch:
        return " or ".join(type_of(s) for s in sch["anyOf"])
    t = sch.get("type", "any")
    if t == "array":
        return f"array of {type_of(sch.get('items', {}))}"
    return t


def check_schema(tool: str, name: str, sch: dict, problems: list) -> None:
    if "$ref" in sch or "$defs" in sch:
        problems.append(f"{tool}.{name}: uses $ref/$defs")
    if "anyOf" in sch:
        kinds = [s.get("type") for s in sch["anyOf"]]
        if len(kinds) != 2 or "null" not in kinds:
            problems.append(f"{tool}.{name}: anyOf other than 'T or null': {kinds}")
        for s in sch["anyOf"]:
            check_schema(tool, name, s, problems)
        return
    t = sch.get("type")
    if t not in SIMPLE:
        problems.append(f"{tool}.{name}: type {t!r}")
    if t == "array":
        if "items" not in sch:
            problems.append(f"{tool}.{name}: array without items")
        else:
            check_schema(tool, name + "[]", sch["items"], problems)


def collect(module: str = "sc4_mcp.server"):
    import importlib
    S = importlib.import_module(module)
    from sc4_mcp.registry import REGISTERED
    tools = asyncio.run(S.mcp.list_tools())
    kinds = {r["name"]: r["kind"] for r in REGISTERED}
    problems = []
    for t in tools:
        if not re.fullmatch(r"[a-zA-Z0-9_-]{1,64}", t.name):
            problems.append(f"{t.name}: name not portable")
        if len(t.description or "") > 1024:
            problems.append(f"{t.name}: description {len(t.description)} > 1024 characters")
        if not (t.description or "").strip():
            problems.append(f"{t.name}: no description")
        if t.annotations is None:
            problems.append(f"{t.name}: no annotations")
        for p, sch in t.inputSchema.get("properties", {}).items():
            if not sch.get("description"):
                problems.append(f"{t.name}.{p}: no description")
            check_schema(t.name, p, sch, problems)
        if t.name not in kinds:
            problems.append(f"{t.name}: not registered through registry.tool")
    return S, tools, kinds, problems


def render(S, tools, kinds, module: str = "sc4_mcp.server") -> str:
    _out, title, target, destroys, special = SERVERS[module]
    order = ["read", "observe", "set", "act", "destructive"]
    meaning = {"read": f"reads {target}, changes nothing", "observe": "reads; has a 'since last call' cursor",
               "set": "sets a value (idempotent)", "act": f"acts in {target}", "destructive": destroys}
    order = [k for k in order if k in set(kinds.get(t.name) for t in tools)]
    L = [f"# Tool reference: {title}", "",
         "<!-- generated by scripts/gen_tool_docs.py from the server's tools/list; do not edit by hand -->", "",
         f"{len(tools)} tools. Every tool takes JSON arguments as described and returns compact JSON text, except "
         f"{special}. Failures are MCP tool errors "
         "(`isError: true`) whose text is JSON `{\"error\": ..., \"hint\": ...}`.", "",
         "Kinds map to the MCP tool annotations each tool carries:", "",
         "| kind | readOnlyHint | destructiveHint | idempotentHint | meaning |", "|---|---|---|---|---|"]
    from sc4_mcp.registry import KINDS
    for k in order:
        a = KINDS[k]
        L.append(f"| {k} | {a.readOnlyHint} | {a.destructiveHint} | {a.idempotentHint} | {meaning[k]} |")
    L += ["", "All tools have openWorldHint false (they act on the local game only).", "", "## Index", "",
          "| tool | kind | what it does |", "|---|---|---|"]
    for t in tools:
        first = re.split(r"(?<=\.)\s", t.description, maxsplit=1)[0]
        L.append(f"| [`{t.name}`](#{t.name}) | {kinds.get(t.name, '?')} | {first} |")
    L += ["", "## Server instructions", "", "Sent to the client at initialization:", "", "> " + S.mcp.instructions,
          ""]
    for t in tools:
        L += [f"## {t.name}", "", f"*{kinds.get(t.name, '?')}*", "", t.description, ""]
        props = t.inputSchema.get("properties", {})
        req = set(t.inputSchema.get("required", []))
        if props:
            L += ["| parameter | type | default | description |", "|---|---|---|---|"]
            for p, sch in props.items():
                default = "required" if p in req else f"`{sch.get('default')!r}`".replace("None", "null") \
                    .replace("True", "true").replace("False", "false")
                desc = sch.get("description", "").replace("|", "\\|")
                L.append(f"| `{p}` | {type_of(sch)} | {default} | {desc} |")
            L.append("")
        else:
            L += ["No parameters.", ""]
    return "\n".join(L)


def main():
    check = "--check" in sys.argv
    bad = False
    for module, (fname, *_rest) in SERVERS.items():
        out = os.path.join(ROOT, "docs", fname)
        S, tools, kinds, problems = collect(module)
        tools = [t for t in tools if t.name in kinds or True]
        text = render(S, tools, kinds, module)
        for p in problems:
            print("PROBLEM", module, p)
        if check:
            cur = open(out, encoding="utf-8").read() if os.path.exists(out) else ""
            stale = cur != text
            if stale:
                print(f"docs/{fname} is stale: run python scripts/gen_tool_docs.py")
            print(f"{module}: {len(tools)} tools, {len(problems)} problems, docs {'stale' if stale else 'current'}")
            bad |= bool(problems) or stale
            continue
        os.makedirs(os.path.dirname(out), exist_ok=True)
        open(out, "w", encoding="utf-8", newline="\n").write(text)
        print(f"wrote {out}: {len(tools)} tools, {len(problems)} problems")
    if check:
        sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
